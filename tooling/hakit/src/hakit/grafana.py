"""How the host Grafana reaches the dashboards of the search path, in place (ADR-0049 §7.5).

The stack's file provider reads `/hakit/dashboards` recursively. Each
`dashboards/` directory of the search path is bind-mounted read-only at
`/hakit/dashboards/<i>`, `i` its entry's position on the path: the base
content's is `0`, which the stack's own compose file mounts too, and an
entry keeps its mount name whether or not the entries before it hold
dashboards. Nothing is copied; an edit of a dashboard file is served at the
provider's next scan.
"""

from __future__ import annotations

from pathlib import Path

import yaml

MOUNT_ROOT = "/hakit/dashboards"


def compose_override(dirs: list[tuple[int, Path]]) -> str:
    """A compose override mounting each `(position, directory)` of `dirs` into the `grafana` service."""
    volumes = [
        {"type": "bind", "source": str(d.resolve()), "target": f"{MOUNT_ROOT}/{i}", "read_only": True}
        for i, d in dirs
    ]
    header = "# Generated by `hakit dashboards --compose-override` from the search path; not edited by hand.\n"
    return header + yaml.safe_dump({"services": {"grafana": {"volumes": volumes}}}, sort_keys=False)
