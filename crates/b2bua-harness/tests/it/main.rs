//! Every b2bua-harness integration test, in ONE binary.
//!
//! Cargo links one binary per `tests/*.rs` file, and each links the whole
//! dependency graph — so the tests live in this directory and are reached
//! through the `mod` lines below instead. A new test file goes here and gets a
//! line added; a file left directly in `tests/` is another copy of the graph,
//! and `just test` refuses it unless `test-binaries.allow` names it. See
//! docs/adr/0030-one-integration-test-binary-per-crate.md.
//!
//! Select one (the workspace build `just test` made, no rebuild):
//! `cargo nextest run --workspace -E 'package(=b2bua-harness) & binary(it)' <module>::<name>`.

